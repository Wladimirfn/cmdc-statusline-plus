// ── preset and value validation / normalisation ─────────────────────────────────────
// A preset only decides segment switches; keys it does not list count as 'off' (otherwise minimal would not be minimal)
const PRESETS: Record<string, Record<string, boolean>> = {
	full: {
		model: true,
		effort: true,
		context: true,
		bar: true,
		percent: true,
		cache: true,
		cost: true,
		speed: true,
		sub: true,
		name: true,
		git: true,
		cwd: true,
	},
	minimal: {model: true, effort: true, context: true, bar: true, percent: true, git: true},
	usage: {context: true, bar: true, percent: true, cache: true, cost: true, sub: true},
	plus: {model: true, effort: true, context: true, bar: true, percent: true, cache: true, cost: true, sub: true},
};

const PRESET_NAMES = ['plus', 'full', 'minimal', 'usage'];

function isPresetName(value: unknown): boolean {
	return typeof value === 'string' && Object.prototype.hasOwnProperty.call(PRESETS, value);
}

// The preset's value for a key; undefined when the key is not a segment key (ascii/raw-model/refresh...) or the preset name is unknown
function presetValue(preset: string, key: string): boolean | undefined {
	if (!FLAG_BY_NAME.get(key)?.segment || !isPresetName(preset)) return undefined;
	return PRESETS[preset][key] ?? false;
}

// Whether this value is usable in the config file: boolean keys must be booleans; numeric keys accept a number or a numeric string but must parse to a non-negative number;
// all other string keys (currently only preset) accept strings only — otherwise {"preset": 123} would pass as usable,
// the report would copy 123 as the effective value while presetName() accepts strings only and actually runs full: the table would lie again.
function acceptsValue(spec: FlagSpec, value: unknown): boolean {
	if (spec.type === 'boolean') return typeof value === 'boolean';
	if (spec.numeric) {
		if (typeof value !== 'string' && typeof value !== 'number') return false;
		const parsed = Number(value);
		return Number.isFinite(parsed) && parsed >= 0;
	}
	return typeof value === 'string';
}

type Lang = 'en';

// Normalisation of the lang key: en / en-US are recognised; anything else returns undefined (the report names it, English is used)
function langOf(value: unknown): Lang | undefined {
	if (typeof value !== 'string') return undefined;
	const head = value.trim().toLowerCase();
	if (head === 'en' || head.startsWith('en-') || head.startsWith('en_')) return 'en';
	return undefined;
}

function describeExpectation(spec: FlagSpec, lang: Lang = 'en'): string {
	if (spec.numeric) return 'non-negative number';
	return spec.type === 'boolean' ? 'true / false' : 'string';
}

// Normalisation of numeric keys: if it parses to a non-negative number, take the integer clamped to max; otherwise fall back to the default.
// flagNumber() and the report table both go through here — otherwise with bar-width: 100 the table would report 100 while the footer uses 40.
function clampedNumber(spec: FlagSpec, value: unknown): number {
	const parsed = Number(value);
	if (!Number.isFinite(parsed) || parsed < 0) return Number(spec.default);
	return Math.min(spec.max ?? Number.MAX_SAFE_INTEGER, Math.floor(parsed));
}

// preset / lang names are case-insensitive (presetName() and langOf() normalise the same way): without this,
// the report table would print 'Minimal' / 'EN' verbatim — disagreeing with the value actually in effect
function canonical(spec: FlagSpec, value: unknown): unknown {
	if (typeof value !== 'string') return value;
	if (spec.name === 'preset') return value.toLowerCase();
	// en-US → en; unrecognised values are kept as-is, reported verbatim by the report, and English is used in practice
	if (spec.name === 'lang') return langOf(value) ?? value;
	return value;
}

