// Command Code mod: a status line under the input box
// Segments: model / effort / context bar / cache hit / session cost / output speed / sub-agents /
//           session name / git branch and changes / current directory name
//
// Deploy: cp index.ts ~/.commandcode/mods/statusline.ts
//         (or install: cmd mods add holtwood/cmdc-statusline -g; dry run without installing: cmd --mod ./index.ts)
// Requires: cmdc >= MIN_HOST_VERSION (currently 1.10.0). Old hosts are not supported: a stale version detected on load
//         disables the mod — one upgrade notice in the message area only, no flag / command / hook / footer. An unreadable version counts as usable (never guess).
// Background: cmdc has no Claude Code style statusLine external-command hook, and the mod's cmd.ui.setStatus is the only
//           interface that can render a persistent status segment under the input box (see mod-builder reference/ui.md); this mod implements it that way.
// The two built-in tables (context windows / prices) are generated by scripts/gen-model-tables.py from the product model list; do not hand-edit.
// Cost is the session total = the history summed from the transcript on resume + the part produced by this process (a restart does not reset it).
// Besides cost, the same resume scan seeds model/effort/context/cache hit of the last request; on a freshly started cmdc with
// no request yet, model/effort are first painted from ~/.commandcode/config.json — otherwise the footer would only fill in
// at the first model_request_end, leaving just git and the directory name in between.
//
// Config (precedence: built-in default < preset < user scope < project scope < command line):
//   ~/.commandcode/statusline.json          user scope
//   <project>/.commandcode/statusline.json  project scope (overrides user scope)
//   --mod-option statusline.<key>=<value>   command line (counts as an explicit override only when the value differs
//                                           from the built-in default — cmdc erases --mod-option values from the argv
//                                           visible to the mod, so 'the default was passed explicitly' cannot be told apart)
//   Available keys: model/effort/context/bar/bar-width/percent/cache/cost/speed/sub/name/git/cwd/
//          preset/raw-model/ascii/refresh/lang (lang only affects the report and the modal copy)
//   preset: plus (model+effort+context+cache+cost+sub, the default) / full (everything) /
//           minimal (model+effort+context+bar+percent+git) / usage (context+cache+cost+sub-agents).
//           It only decides which segments are on; writing a single key overrides it. Render switches (ascii/raw-model) are unrelated to it.
//
// Why flag names carry a prefix but config keys do not: the host keeps mod flag values in a process-wide table indexed by
// name (measured: addFlag writes defaults first come first served, getFlag always reads from that table, and the type of a
// --mod-option is decided by the first declarer) — two mods declaring the same flag silently cross values and the other side
// cannot even read its own default. Config files do not have this problem: the file name statusline.json is itself the namespace.
// So only flag names sent to the host carry the statusline. prefix; keys (JSON, report table, selector) stay short; flagName() is the only derivation point.
//
// Self-service troubleshooting and config (no need to dig through the README):
//   /statusline          prints the full 'key / default / effective / source' table and warns separately about unknown
//                        (typo) and wrongly typed keys from the JSON; file sources are listed as well
//   /statusline config   edits interactively via cmd.ui.select/input/confirm; writes and repaints right away, no /reload
//
// Narrow terminals: degrade by priority (drop cwd → speed → effort → sub-agents → cache → session name → cost → changes first,
//         context degrades step by step from bar+token+percent, branch goes last, the model is never dropped), and listen to resize to repaint immediately.

