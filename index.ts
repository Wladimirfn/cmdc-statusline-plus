type Strings = {readonly [K in keyof (typeof L10N)['en']]: (typeof L10N)['en'][K] extends string ? string : (typeof L10N)['en'][K]};

// ── mod factory ─────────────────────────────────────────────────────────────────────
export default function (cmd: ModApi): void {
	// Read the config file first (pure file IO, no registered flag needed): the language of the version notice and of the flag
	// descriptions depends only on lang in the file — both are produced at registration time, when getFlag is not available yet.
	let {config, sources: configSources, origin: configOrigin, broken: configBroken} = loadConfig(
		cmd.cwd,
	);
	const fileLang = langOf(config['lang']) ?? 'en';

	// Version gate: this mod does not support old hosts and does not degrade.
	// A readable version that is genuinely too old → notify to upgrade and disable immediately, not even registering flags or commands —
	// better to do nothing at all than to leave a footer that 'reacts but is wrong'.
	// When the version cannot be read, do not guess (nothing can be decided then; treat it as usable and show cmdc=unknown in the report).
	const host = hostVersion();
	if (host !== undefined && !versionAtLeast(host, MIN_HOST_VERSION)) {
		const message = L10N[fileLang].oldHost(MIN_HOST_VERSION, host);
		try {
			cmd.ui.notify(message, 'error');
		} catch {
			// The notice channel may not exist on an old host; fall back to the terminal so the notice does not vanish entirely
			console.error(message);
		}
		return;
	}

	for (const spec of FLAG_SPECS) {
		cmd.addFlag(flagName(spec.name), {
			type: spec.type,
			default: spec.default,
			// The description text can only look at lang from the config file right now: the flag is not registered yet, so CLI overrides are out of reach
			description: fileLang === 'en' ? spec.descriptionEn : spec.description,
		});
	}

	let session = freshSession();
	let requestStartedAt = 0;
	let timer: NodeJS.Timeout | undefined;
	// git's adaptive gate: when the read finished (not when it started) + the last measured duration + whether 'slow' was already reported
	let gitFinishedAt = 0;
	let gitDurationMs = 0;
	let gitSlowNotified = false;
	let gitReading = false;

	const presetName = (): string => {
		const cli = cmd.getFlag(flagName('preset'));
		const configured = config['preset'];
		// The command line counts as an explicit override only when it differs from the built-in default (the host erases =value from argv)
		const raw =
			typeof cli === 'string' && cli !== 'full'
				? cli
				: typeof configured === 'string'
					? configured
					: 'full';
		return raw.toLowerCase();
	};

	// The effective source is data, not a string: the copy is produced at render time under the current lang,
	// otherwise an English report would be mixed with Chinese 'CLI / preset x' text.
	// The CLI entry carries the key name: the source column must say which flag 'command line' actually means — the report and selector
	// use short keys while the command line needs the prefixed flag name; the two names must be matched up here.
	type FlagSource =
		| {kind: 'cli'; key: string}
		| {kind: 'file'; path?: string}
		| {kind: 'preset'; name: string}
		| {kind: 'default'};

	// The single value-resolution entry point: flag() / flagNumber() / the report table all go through it,
	// so 'the effective value written in the table' and 'the value actually used' can never drift.
	// Precedence: command line (when different from the built-in default) > config file > preset > built-in default.
	const resolveFlag = (name: string): {value: unknown; source: FlagSource} => {
		const spec = FLAG_BY_NAME.get(name);
		const base = spec?.default;
		const cli = cmd.getFlag(flagName(name));
		if (spec && typeof cli === typeof base && cli !== base) {
			return {value: canonical(spec, cli), source: {kind: 'cli', key: name}};
		}
		const configured = config[name];
		if (spec && configured !== undefined && acceptsValue(spec, configured)) {
			return {value: canonical(spec, configured), source: {kind: 'file', path: configOrigin[name]}};
		}
		const preset = presetValue(presetName(), name);
		// Do not report 'preset x' when the preset value equals the built-in default — that line carries no information (full is an alias of the built-in default)
		if (preset !== undefined && preset !== base) {
			return {value: preset, source: {kind: 'preset', name: presetName()}};
		}
		return {value: preset ?? base, source: {kind: 'default'}};
	};

	const currentLang = (): Lang => langOf(resolveFlag('lang').value) ?? 'en';
	const s = (): Strings => L10N[currentLang()];

	const sourceText = (source: FlagSource): string => {
		const t = s();
		switch (source.kind) {
			case 'cli':
				return t.cliFlag(flagName(source.key));
			case 'file':
				return source.path === undefined
					? t.builtin
					: source.path === userConfigPath()
						? t.userScope
						: t.projectScope;
			case 'preset':
				return t.presetSource(source.name);
			default:
				return t.builtin;
		}
	};

	// The description language also switches live with the effective lang (the text registered at load time cannot be changed, but the interactive list is drawn by us)
	const specDesc = (spec: FlagSpec): string =>
		currentLang() === 'en' ? spec.descriptionEn : spec.description;

	// No fallback parameter: the default comes from the registry alone; passing another one at a call site would only create a second source of truth
	const flag = (name: string): boolean => resolveFlag(name).value === true;

	// The ceiling comes from spec.max in the registry instead of being passed at each call site (two copies would drift eventually)
	const flagNumber = (name: string): number => {
		const spec = FLAG_BY_NAME.get(name);
		return spec ? clampedNumber(spec, resolveFlag(name).value) : 0;
	};

	const reloadConfig = (): void => {
		({config, sources: configSources, origin: configOrigin, broken: configBroken} = loadConfig(
			cmd.cwd,
		));
	};

	// Keys present in the JSON that we do not know (typos), keys with unusable values, and unrecognised preset / lang values — all of
	// them are named, otherwise a user who edited the config gets no feedback and will just assume the feature is broken
	const configWarnings = (): string[] => {
		const t = s();
		const warnings: string[] = [];
		for (const [key, path] of Object.entries(configOrigin)) {
			const spec = FLAG_BY_NAME.get(key);
			if (!spec) {
				warnings.push(t.unknownKey(key, sourceText({kind: 'file', path})));
				continue;
			}
			if (!acceptsValue(spec, config[key])) {
				warnings.push(
					t.badValue(
						key,
						describeExpectation(spec, currentLang()),
						JSON.stringify(config[key]),
						sourceText({kind: 'file', path}),
					),
				);
			}
		}
		// Case-insensitive, so the check must normalise first — otherwise {"preset":"Minimal"} would be misreported as an unknown preset
		const cliPreset = cmd.getFlag(flagName('preset'));
		const configured = config['preset'];
		const bogus =
			typeof cliPreset === 'string' && cliPreset !== 'full' && !isPresetName(cliPreset.toLowerCase())
				? {value: cliPreset, where: t.cliFlag(flagName('preset'))}
				: typeof configured === 'string' && !isPresetName(configured.toLowerCase())
					? {value: configured, where: sourceText({kind: 'file', path: configOrigin['preset']})}
					: undefined;
		if (bogus) {
			// The outcome must be stated per the preset that will actually take effect: when the command line overrides the config, claiming 'treated as full' would be false
			const effective = isPresetName(presetName()) ? presetName() : 'full';
			warnings.push(t.unknownPreset(JSON.stringify(bogus.value), bogus.where, effective));
		}
		// lang is like preset: a string that cannot be recognised (e.g. "fr") → named + English used in practice; non-strings are already caught by badValue above
		const cliLang = cmd.getFlag(flagName('lang'));
		const confLang = config['lang'];
		const bogusLang =
			typeof cliLang === 'string' && langOf(cliLang) === undefined
				? {value: cliLang, where: t.cliFlag(flagName('lang'))}
				: typeof confLang === 'string' && langOf(confLang) === undefined
					? {value: confLang, where: sourceText({kind: 'file', path: configOrigin['lang']})}
					: undefined;
		if (bogusLang) {
			// State the outcome per what actually takes effect, as with preset: when the command line lang=en overrides a bad value in the file,
			// reporting a fixed fallback instead of the effective language would be a lie
			warnings.push(t.unknownLang(JSON.stringify(bogusLang.value), bogusLang.where, currentLang()));
		}
		return warnings;
	};

	const barWidth = (): number => flagNumber('bar-width');

	const asciiOnly = (): boolean => flag('ascii') || process.env.TERM === 'dumb';

	const colorEnabled = (): boolean => !process.env.NO_COLOR && !asciiOnly();

	const colorMode = (): ColorMode => {
		if (asciiOnly()) return 'ascii';
		return /truecolor|24bit/i.test(process.env.COLORTERM ?? '') ? 'truecolor' : 'ansi256';
	};

	const segments = (): Segments => ({
		model: flag('model'),
		effort: flag('effort'),
		context: flag('context'),
		bar: flag('bar'),
		percent: flag('percent'),
		cache: flag('cache'),
		cost: flag('cost'),
		speed: flag('speed'),
		sub: flag('sub'),
		name: flag('name'),
		git: flag('git'),
		cwd: flag('cwd'),
	});

	const terminalWidth = (): number => {
		const columns = process.stdout.columns ?? 0;
		if (!Number.isFinite(columns) || columns <= 0) return 0;
		return Math.max(20, columns - 2);
	};

	const cwdName = (): string | undefined => cwdBasename(cmd.cwd);

	const seedTitle = (): void => {
		const snapshot = session.snapshot;
		if (!flag('name') || !session.id || snapshot.title) return;
		const title = readSessionTitle(session.id, cmd.cwd);
		if (title) snapshot.title = title;
	};

	// Display value = the history restored from the transcript + the part produced by this process (both counted once, never twice)
	const updateCost = (): void => {
		session.snapshot.costUsd = session.seededCost + session.sessionCost;
	};

	// Model / effort from the config: fill only the still-empty segments; once the first request returns there is no need to read the disk
	const seedFromConfig = (): void => {
		const snapshot = session.snapshot;
		if (snapshot.model && snapshot.effort) return;
		const {model, reasoningEffort} = readUserConfig();
		if (!snapshot.model && model) snapshot.model = model;
		if (!snapshot.effort && snapshot.model) snapshot.effort = reasoningEffort[snapshot.model];
	};

	// An event that carries a sessionId different from the current session → drop the whole event: after a session swap,
	// late events of the old session (in-flight request completion, titled, turn_end, ...) must not be written into the new session's state.
	// If either side does not know the id it cannot be decided, so let it through — better to paint once too often than to filter out real events.
	const forCurrentSession = (event: unknown): boolean => {
		const id = (event as {sessionId?: unknown}).sessionId;
		return typeof id !== 'string' || session.id === undefined || id === session.id;
	};

	// Resuming a session: the transcript records what actually happened, which beats the guesses read from the config
	const seedSession = async (): Promise<void> => {
		if (session.seeded || !session.id) return;
		session.seeded = true;
		const snapshot = session.snapshot;
		const seed = await readSessionSeed(session.id, cmd.cwd);
		// The session may have been swapped while awaiting: that transcript belongs to the old session, discard it whole
		if (!seed || session.snapshot !== snapshot) return;
		if (seed.drifted) session.seedDrifted = true;
		if (seed.costUsd > 0) session.seededCost = seed.costUsd;
		if (seed.model) snapshot.model = seed.model;
		if (seed.effort) snapshot.effort = seed.effort;
		if (seed.usage) {
			if (typeof seed.usage.inputTokens === 'number') {
				snapshot.contextTokens = seed.usage.inputTokens;
			}
			const hit = cacheHitRate(seed.usage);
			if (hit !== undefined) snapshot.cacheHit = hit;
		}
		updateCost();
		refresh();
	};

	// Three things can be restored at startup: model/effort from the config, the session name, and the history totals from the transcript.
	// Both entry points (onSessionStart and run_start) must run the same set — either can arrive first, and repeating is idempotent.
	const seedFromKnownSources = (): void => {
		seedFromConfig();
		seedTitle();
		void seedSession();
	};

	// Notify once when a single read takes longer than the configured refresh interval: that is exactly the invisible failure of 'users do not know their repo is slow'
	const noteSlowGit = (): void => {
		if (gitSlowNotified) return;
		const intervalMs = flagNumber('refresh') * 1000;
		if (intervalMs <= 0 || gitDurationMs < intervalMs) return;
		gitSlowNotified = true;
		cmd.ui.notify(
			s().slowGit(
				(gitDurationMs / 1000).toFixed(1),
				intervalMs / 1000,
				Math.round(gitGapMs(gitDurationMs) / 1000),
			),
			'warning',
		);
	};

	const readGit = async (): Promise<void> => {
		// Adaptive gate: a slow repo widens the interval by itself (the interval is measured from when the last read finished, not when it started —
		// otherwise an 8 second call returns after the 5 second TTL has long expired and every later event triggers another read)
		if (gitReading || Date.now() - gitFinishedAt < gitGapMs(gitDurationMs)) return;
		gitReading = true;
		const startedAt = Date.now();
		// Timeout backstop: a hung git (locks, dead mounts, huge repos) must not leave this read pending forever
		const controller = new AbortController();
		const killer = setTimeout(() => controller.abort(), GIT_TIMEOUT_MS);
		try {
			const {stdout, code} = await cmd.exec({
				command: 'git',
				args: ['status', '--porcelain=v1', '-b'],
				cwd: cmd.cwd,
				signal: controller.signal,
			});
			const info =
				code === 0
					? parseGitStatus(stdout)
					: {
							isRepo: false,
							ahead: 0,
							behind: 0,
							staged: 0,
							modified: 0,
							untracked: 0,
						};
			// git results are repo properties and do not change with the session: write them into the 'current' session (a swap while awaiting does not lose this read)
			const snapshot = session.snapshot;
			snapshot.isRepo = info.isRepo;
			snapshot.branch = info.branch;
			snapshot.ahead = info.ahead;
			snapshot.behind = info.behind;
			snapshot.staged = info.staged;
			snapshot.modified = info.modified;
			snapshot.untracked = info.untracked;
		} catch {
			session.snapshot.isRepo = false;
			session.snapshot.branch = undefined;
		} finally {
			clearTimeout(killer);
			gitReading = false;
			gitDurationMs = Date.now() - startedAt;
			gitFinishedAt = Date.now();
			noteSlowGit();
			// Paint again once git returns; in a slow repo that only makes the git segment appear a bit later, it does not hold up other segments
			paint();
		}
	};

	const composer = (): string =>
		composeLine(session.snapshot, segments(), {
			color: colorEnabled(),
			rawModel: flag('raw-model'),
			mode: colorMode(),
			barWidth: barWidth(),
			maxWidth: terminalWidth(),
			cwd: cwdName(),
		});

	// Whether this run renders the footer at all. Two things merge into one decision here:
	//   status === false  → the host explicitly says it does not paint (headless)
	//   capabilities missing → a 1.9.0 style old host, and the version gate is best-effort (it does not guess when the version is unreadable and lets it through),
	//                       so execution reaches here. Reading .status directly would turn every event into a mod_error,
	//                       and falling back to 'paint nothing' is more decent than erroring continuously in the user's session.
	// The report must tell these two cases apart, so it does not use this function and reads the three-state value directly.
	const rendersFooter = (): boolean => cmd.ui.capabilities?.status === true;

	// ---- cmdc-statusline-plus: account 5h / weekly windows ----
	// Reads the UNDOCUMENTED endpoint api.commandcode.ai/alpha/billing/credits using the CLI
	// key from ~/.commandcode/auth.json. Any failure clears the segment; never throws.
	const USAGE_ENDPOINT = 'https://api.commandcode.ai/alpha/billing/credits';
	const USAGE_POLL_MS = 120_000;
	type UsageWindow = {used?: number; cap?: number; resetAt?: number};
	let limitsData: {fiveHour?: UsageWindow; weekly?: UsageWindow} | null = null;
	let limitsTimer: ReturnType<typeof setInterval> | undefined;
	// Colour a value with the module palette (composeLine paints with its own local helper).
	const sgr = (code: string, text: string): string =>
		colorEnabled() ? `${code}${text}${ANSI.reset}` : text;
	const usageUntil = (resetAt?: number): string => {
		if (typeof resetAt !== 'number') return '';
		const ms = resetAt - Date.now();
		if (ms <= 0) return '';
		const m = Math.floor(ms / 60000);
		const d = Math.floor(m / 1440);
		const h = Math.floor((m % 1440) / 60);
		if (d > 0) return `↻${d}d${h}h`;
		if (h > 0) return `↻${h}h${m % 60}m`;
		return `↻${m}m`;
	};
	// Same visual language as the built-in segments: the shared gradient bar, dim separators,
	// and the context colour rule (>=90 red, >=80 yellow, else gray).
	const usageText = (): string => {
		const data = limitsData;
		if (!data) return '';
		const segment = (label: string, win?: UsageWindow): string => {
			if (!win || typeof win.used !== 'number' || typeof win.cap !== 'number' || win.cap <= 0) return '';
			const percent = (win.used / win.cap) * 100;
			const code = percent >= 90 ? ANSI.red : percent >= 80 ? ANSI.yellow : ANSI.gray;
			const bar = renderBar(percent, barWidth(), colorMode(), colorEnabled());
			const reset = usageUntil(win.resetAt);
			return [sgr(ANSI.gray, label), bar, sgr(code, `${Math.round(percent)}%`), reset ? sgr(ANSI.dim, reset) : '']
				.filter(Boolean)
				.join(' ');
		};
		return [segment('5h', data.fiveHour), segment('week', data.weekly)]
			.filter(Boolean)
			.join(sgr(ANSI.dim, SEP));
	};
	const readUsage = async (): Promise<{fiveHour?: UsageWindow; weekly?: UsageWindow} | null> => {
		try {
			const raw = readFileSync(join(homedir(), '.commandcode', 'auth.json'), 'utf8');
			const key = (JSON.parse(raw) as {apiKey?: unknown}).apiKey;
			if (typeof key !== 'string' || key.length === 0) return null;
			const res = await fetch(USAGE_ENDPOINT, {headers: {Authorization: `Bearer ${key}`}});
			if (!res.ok) return null;
			const data = (await res.json()) as {windowLimits?: {fiveHour?: UsageWindow; weekly?: UsageWindow}};
			return data.windowLimits ?? null;
		} catch {
			return null;
		}
	};
	const refreshLimits = async (): Promise<void> => {
		limitsData = await readUsage();
		paint();
	};
	const startLimitsTimer = (): void => {
		void refreshLimits();
		if (!limitsTimer) {
			limitsTimer = setInterval(() => {
				void refreshLimits();
			}, USAGE_POLL_MS);
			limitsTimer.unref?.();
		}
	};
	const stopLimitsTimer = (): void => {
		if (limitsTimer) {
			clearInterval(limitsTimer);
			limitsTimer = undefined;
		}
		limitsData = null;
	};

	// Repainting is synchronous and idempotent (the host dedupes identical text itself), so it never waits for git:
	// refresh() used to await git before painting, so an 8 second git status stalled model/cost/context for 8 seconds as well.
	const paint = (): void => {
		if (!rendersFooter()) return;
		const line = [sgr(ANSI.magenta, BRAND), composer(), usageText()]
			.filter(Boolean)
			.join(sgr(ANSI.dim, SEP));
		cmd.ui.setStatus(line || null);
	};

	const refresh = (): void => {
		// If this run does not render the footer (headless), do nothing at all: not even a git process should start
		if (!rendersFooter()) return;
		paint();
		// Whether git is actually read is decided by readGit's adaptive gate; this only sends the request out
		if (flag('git')) void readGit();
	};

	const startTimer = (): void => {
		const seconds = flagNumber('refresh');
		if (seconds <= 0 || timer) return;
		// The timer's only job is 'external changes': in-process events refresh anyway.
		// It no longer pokes a timestamp to force a read — whether one is allowed is decided solely by the gate computed from the measured duration.
		timer = setInterval(() => refresh(), seconds * 1000);
		timer.unref?.();
	};

	const stopTimer = (): void => {
		if (!timer) return;
		clearInterval(timer);
		timer = undefined;
	};

	const onResize = (): void => {
		refresh();
	};

	cmd.hooks({
		onSessionStart: info => {
			const data = info as unknown as SessionEvent;
			const id = typeof data.sessionId === 'string' ? data.sessionId : undefined;
			// The host swaps sessions in the same process (onSessionEnd's reason can be 'replaced'): when the id changes, rebuild everything,
			// otherwise the previous session's name/cost/seed flags leak straight into the new session. Re-firing with the same id must not reset —
			// that would zero the running session's totals.
			if (id !== undefined && id !== session.id) {
				session = freshSession(id);
				requestStartedAt = 0;
			}
			seedFromKnownSources();
			startTimer();
			startLimitsTimer();
			// Idempotent: if start fires again after a session swap, avoid stacking listeners
			process.stdout.off('resize', onResize);
			process.stdout.on('resize', onResize);
			// The first git read of a new session is always worth it (a session swap must not be blocked by the previous session's backoff gate)
			gitFinishedAt = 0;
			refresh();
		},
		onSessionEnd: () => {
			stopTimer();
			stopLimitsTimer();
			process.stdout.off('resize', onResize);
			cmd.ui.setStatus(null);
		},
	});

	cmd.on('run_start', event => {
		const data = event as unknown as SessionEvent;
		if (!forCurrentSession(event)) return;
		// Adopt an id only when there is none yet: a run's sessionId should belong to the current session,
		// and resetting on a different id would wipe the whole session state for one unexpected nested run
		if (session.id === undefined && typeof data.sessionId === 'string') session.id = data.sessionId;
		seedFromKnownSources();
		refresh();
	});

	cmd.on('session_titled', event => {
		if (!forCurrentSession(event)) return;
		const data = event as unknown as {title?: unknown};
		if (typeof data.title === 'string' && data.title.trim()) {
			session.snapshot.title = data.title;
		}
		refresh();
	});

	cmd.on('model_request_start', event => {
		if (!forCurrentSession(event)) return;
		const data = event as unknown as ModelEvent;
		if (typeof data.model === 'string') session.snapshot.model = data.model;
		requestStartedAt = Date.now();
		refresh();
	});

	cmd.on('model_request_end', event => {
		if (!forCurrentSession(event)) return;
		const data = event as unknown as ModelEvent;
		const snapshot = session.snapshot;
		if (typeof data.model === 'string') snapshot.model = data.model;
		if (typeof data.effort === 'string') snapshot.effort = data.effort;
		if (typeof data.usage?.inputTokens === 'number') {
			snapshot.contextTokens = data.usage.inputTokens;
		}
		if (data.usage) {
			const hit = cacheHitRate(data.usage);
			if (hit !== undefined) snapshot.cacheHit = hit;
			const cost = estimateCost(data.usage, snapshot.model);
			if (cost > 0) {
				session.sessionCost += cost;
				updateCost();
			}
			const output = data.usage.outputTokens ?? 0;
			const elapsed = (Date.now() - requestStartedAt) / 1000;
			if (requestStartedAt > 0 && elapsed > 0 && output > 0) {
				snapshot.speed = output / elapsed;
			}
		}
		refresh();
	});

	// Sub-agent model requests do not go through model_request_* (measured), so their usage can only be folded in from subagent_stop;
	// the product does not count sub-agent tokens in the transcript either, so only tokens are accumulated here, not exact cost.
	cmd.on('subagent_stop', event => {
		if (!forCurrentSession(event)) return;
		const data = event as unknown as SubagentStopEvent;
		if (typeof data.tokensUsed === 'number' && data.tokensUsed > 0) {
			session.snapshot.subTokens += data.tokensUsed;
			refresh();
		}
	});

	cmd.on('turn_end', event => {
		if (!forCurrentSession(event)) return;
		refresh();
	});

	cmd.on('config_setting_changed', event => {
		if (!forCurrentSession(event)) return;
		const data = event as unknown as ConfigChangedEvent;
		if (data.setting === 'model' && typeof data.value === 'string') {
			session.snapshot.model = data.value;
			// effort is stored per model, so a model change must change the value too — clear it when the config has none; keeping the previous model's effort would be wrong
			session.snapshot.effort = readUserConfig().reasoningEffort[data.value];
		}
		// Repaint right after /effort changes instead of waiting for the next model_request_end
		if (data.setting === 'effort' && typeof data.value === 'string') {
			session.snapshot.effort = data.value;
		}
		refresh();
	});

	// Display value of a key: numeric keys show the clamped value. Showing the raw config value would be wrong —
	// with bar-width: 100 the footer uses 40 (spec.max), so reporting 100 in the table would be a lie.
	const displayValue = (spec: FlagSpec, value: unknown): string => {
		if (spec.numeric) return String(clampedNumber(spec, value));
		if (typeof value === 'boolean') return value ? 'true' : 'false';
		return String(value ?? '-');
	};

	const presetHint = (name: string): string =>
		Object.entries(PRESETS[name] ?? {})
			.filter(([, on]) => on)
			.map(([key]) => key)
			.join(' + ');

	// Diagnostics: a 'key / default / effective / source' table + warnings.
	// It solves both 'the key names have no entry point' (no README digging) and 'changed it, no effect, no feedback' (unknown keys / bad values are named).
	const statuslineReport = (): string => {
		const t = s();
		const snapshot = session.snapshot;
		const plain = composeLine(snapshot, segments(), {
			color: false,
			rawModel: true,
			mode: 'ascii',
			barWidth: barWidth(),
			maxWidth: 0,
			cwd: cwdName(),
		});
		const window = contextWindowFor(snapshot.model);
		const priced = modelPriceFor(snapshot.model) !== undefined;
		const subEstimate =
			snapshot.subTokens > 0 && snapshot.costUsd > 0 && snapshot.contextTokens
				? (snapshot.costUsd / snapshot.contextTokens) * snapshot.subTokens
				: 0;
		const state = [
			`model=${snapshot.model ?? '-'}`,
			`effort=${snapshot.effort ?? '-'}`,
			`ctx=${snapshot.contextTokens ? formatTokens(snapshot.contextTokens) : '-'}${
				window ? `/${formatWindow(window)}` : t.windowUnknown
			}`,
			`cache=${snapshot.cacheHit !== undefined ? formatRate(snapshot.cacheHit) : '-'}`,
			`cost=${snapshot.costUsd > 0 ? formatCost(snapshot.costUsd) : '-'}${
				session.seededCost > 0 ? t.restored(formatCost(session.seededCost)) : ''
			}${priced ? '' : t.priceUnknown}`,
			`speed=${snapshot.speed ? `${Math.round(snapshot.speed)} tok/s` : '-'}`,
			`sub=${snapshot.subTokens > 0 ? `${formatTokens(snapshot.subTokens)}${t.subNote(formatCost(subEstimate))}` : '-'}`,
			`name=${snapshot.title ?? '-'}`,
			`git=${snapshot.isRepo ? (snapshot.branch ?? '-') : t.notRepo}`,
			`render=${asciiOnly() ? 'ascii' : colorMode()}`,
			`width=${terminalWidth() || t.unknown}`,
			`cmdc=${host ?? t.unknown}${t.requires(MIN_HOST_VERSION)}`,
			// Three states instead of two: the host saying 'not rendering' (headless) and the host lacking the property altogether (an old host whose
			// version was unreadable so the gate let it through) are different things; reporting the latter as headless would be a lie
			`footer=${
				cmd.ui.capabilities
					? cmd.ui.capabilities.status
						? t.rendering
						: t.headless
					: t.unknown
			}`,
		].join(' | ');

		const pad = (text: string, width: number): string => text.padEnd(width, ' ');
		const rows = FLAG_SPECS.map(spec => {
			const {value, source} = resolveFlag(spec.name);
			return [spec.name, String(spec.default), displayValue(spec, value), sourceText(source)];
		});
		// Column widths are computed from the content: hard-coded widths glue a column to the next one when a value grows (preset=minimal is exactly 7 characters)
		const columnWidth = (index: number): number =>
			Math.max(...rows.map(row => row[index].length)) + 1;
		const table = rows.map(row =>
			row.map((cell, index) => pad(cell, columnWidth(index))).join('').trimEnd(),
		);
		// Name both candidate files and mark whether this one could actually be read — listing only the 'loaded' ones would render
		// 'file exists but is broken' as 'there is no config file', which is exactly the case users most need to know about
		const files = [userConfigPath(), projectConfigPath(cmd.cwd)]
			.map(path =>
				configSources.includes(path)
					? `${path}${t.activeTag}`
					: configBroken.includes(path)
						? `${path}${t.brokenTag}`
						: path,
			)
			.join(' + ');

		const lines = [
			`${t.lineLabel}${t.colon}${plain}`,
			`${t.dataLabel}${t.colon}${state}`,
			t.configHead,
			...table,
			`${t.filesLabel}${t.colon}${files}`,
		];
		if (configSources.length === 0) {
			// Do not write 'everything falls back to the built-in default': without a config file the command line and presets can still set values,
			// and saying so would contradict the 'preset x / CLI' rows in the table above
			lines.push(t.noFilesNote);
		}
		for (const path of configBroken) {
			lines.push(`⚠ ${t.brokenFile(path)}`);
		}
		if (session.seedDrifted) {
			lines.push(`⚠ ${t.seedDrift}`);
		}
		for (const warning of configWarnings()) lines.push(`⚠ ${warning}`);
		lines.push(t.tip);
		return lines.join('\n');
	};

	// Interactive config: goes through cmd.ui.select/input/confirm (real modals in the TUI).
	// Under headless, select returns undefined, so the whole flow naturally falls back to 'print the diagnostics' and never writes files blindly.
	const configureStatusline = async (ui: ModApi['ui']): Promise<string> => {
		// The interaction modal may not exist (headless returns undefined; unusual hosts may lack these methods entirely,
		// or even ui itself): when one is missing, do not throw and become a mod_error, just fall back to printing the diagnostics
		const canAsk =
			typeof ui?.select === 'function' &&
			typeof ui?.input === 'function' &&
			typeof ui?.confirm === 'function';
		if (!canAsk) {
			return [s().needTui, s().noModal, '', statuslineReport()].join('\n');
		}
		// The scope keeps a semantic key, not a label: if the user changes lang mid-flow, the old label string no longer matches
		const scopePick = await ui.select({
			title: s().scopeTitle(presetName()),
			options: [
				{label: s().userLevel, description: `${userConfigPath()} · ${s().allProjects}`},
				{label: s().projectLevel, description: `${projectConfigPath(cmd.cwd)} · ${s().thisProject}`},
			],
		});
		if (scopePick === undefined) {
			return [s().noModalShort, '', statuslineReport()].join('\n');
		}
		const scopeKey = scopePick === s().userLevel ? 'user' : 'project';
		const path = scopeKey === 'user' ? userConfigPath() : projectConfigPath(cmd.cwd);
		const scopeLabel = () => (scopeKey === 'user' ? s().userLevel : s().projectLevel);
		const changes: string[] = [];
		const notes: string[] = [];

		for (;;) {
			const t = s();
			const pick = await ui.select({
				title: t.editorTitle(scopeLabel(), changes.length),
				options: [
					...FLAG_SPECS.map(spec => {
						const {value} = resolveFlag(spec.name);
						const shown = spec.numeric
							? String(clampedNumber(spec, value))
							: typeof value === 'boolean'
								? value
									? t.on
									: t.off
								: String(value);
						return {label: spec.name, description: `${shown} · ${specDesc(spec)}`};
					}),
					{label: t.done, description: t.doneDesc},
				],
			});
			if (pick === undefined || pick === t.done) break;
			const spec = FLAG_BY_NAME.get(pick);
			if (!spec) continue;

			let value: unknown;
			if (spec.name === 'preset') {
				value = await ui.select({
					title: t.presetTitle,
					options: PRESET_NAMES.map(name => ({label: name, description: presetHint(name)})),
				});
			} else if (spec.name === 'lang') {
				// lang is a string key but not free input: writing anything else only earns the 'unknown language' warning
				value = await ui.select({
					title: t.langTitle,
					options: [
						{label: 'en', description: 'English'},
					],
				});
			} else if (spec.numeric) {
				const typed = await ui.input({
					title: t.numberTitle(spec.name, describeExpectation(spec, currentLang()), spec.max),
					placeholder: String(spec.default),
				});
				const parsed = Number(typed);
				if (typed !== undefined && Number.isFinite(parsed)) value = parsed;
			} else {
				const picked = await ui.select({
					title: t.boolTitle(spec.name, specDesc(spec)),
					options: [
						{label: t.on, description: 'true'},
						{label: t.off, description: 'false'},
					],
				});
				if (picked !== undefined) value = picked === t.on;
			}
			if (value === undefined) continue;

			// Show 'what is actually in effect' rather than 'what this file says': a key of the same name may be overridden by another file,
			// and looking only at this file would make the user think the change is redundant (or, conversely, that it will take effect)
			const effective = resolveFlag(spec.name);
			const agreed = await ui.confirm({
				title: s().confirmTitle(spec.name, JSON.stringify(value)),
				message: s().confirmBody(
					path,
					spec.name,
					displayValue(spec, effective.value),
					sourceText(effective.source),
					JSON.stringify(value),
				),
			});
			if (!agreed) continue;

			try {
				writeConfigKey(path, spec.name, value);
			} catch (error) {
				ui.notify(s().writeFailed(error instanceof Error ? error.message : String(error)), 'error');
				continue;
			}
			changes.push(`${spec.name}=${JSON.stringify(value)}`);
			reloadConfig();
			// refresh changes the timer interval: restart it, otherwise 'no /reload needed' would be a lie
			stopTimer();
			startTimer();
			refresh();
			// Written to user scope while project scope has a key of the same name (or the command line overrides it) → the footer will not change.
			// This must be said to the user's face, otherwise they see 'written' with no visible change and assume the feature is broken
			const applied = resolveFlag(spec.name);
			if (displayValue(spec, applied.value) !== displayValue(spec, value)) {
				notes.push(
					s().shadowed(
						spec.name,
						displayValue(spec, applied.value),
						sourceText(applied.source),
						scopeLabel(),
					),
				);
			}
		}

		const head =
			changes.length > 0 ? s().wrote(path, changes) : s().noChanges;
		return [head, ...notes.map(note => `⚠ ${note}`), '', statuslineReport()].join('\n');
	};

	cmd.addCommand({
		name: 'statusline',
		description: 'inspect the status line and config sources; `/statusline config` edits interactively',
		handler: async (context: {args?: unknown; ui?: ModApi['ui']}) => {
			const sub = String(context?.args ?? '').trim().toLowerCase();
			if (sub === 'config') {
				return {message: await configureStatusline(context?.ui ?? cmd.ui)};
			}
			return {message: statuslineReport()};
		},
	});
}

