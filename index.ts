// Adaptive backoff for slow repos: the allowed interval = max(GIT_TTL_MS, GIT_BACKOFF × the last measured duration),
// i.e. 'git takes at most 20% of wall-clock time'. A normal repo always stays under the 5 second floor, exactly as before.
const GIT_BACKOFF = 5;

// Loop bound for narrow-terminal degradation, see composeLine: never reached in practice, a backstop for logic bugs
const DROP_STEPS_MAX = 64;

export function gitGapMs(durationMs: number): number {
	return Math.max(GIT_TTL_MS, GIT_BACKOFF * Math.max(0, durationMs));
}

const ANSI_PATTERN = /\u001b\[[0-9;]*m/g;

// Narrow-terminal drop order: the higher the number, the earlier it is dropped; 0 = never dropped.
// Note these keys are not flag keys: the git segment is split into gitBranch / gitChanges entries at render time,
// each with its own rank here. The entry key type is taken from this table (DropKey), so a wrong name in push()
// is a compile error rather than silently landing on a middle priority as before.
const DROP_ORDER = {
	cwd: 11,
	speed: 10,
	effort: 9,
	sub: 8,
	cache: 7,
	name: 6,
	cost: 5,
	gitChanges: 4,
	context: 3,
	gitBranch: 2,
	model: 0,
} as const;

type DropKey = keyof typeof DROP_ORDER;

const ANSI = {
	reset: '\u001b[0m',
	bold: '\u001b[1m',
	dim: '\u001b[2m',
	red: '\u001b[31m',
	green: '\u001b[32m',
	yellow: '\u001b[33m',
	cyan: '\u001b[36m',
	magenta: '\u001b[35m',
	gray: '\u001b[90m',
};

