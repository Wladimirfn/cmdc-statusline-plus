type SessionSeed = {
	readonly costUsd: number;
	readonly model?: string;
	readonly effort?: string;
	readonly usage?: Usage;
	/** the transcript has usage+model records but not a single tail anchor matched → the product's record format may have changed */
	readonly drifted?: boolean;
};

// Assistant message entries put usage / model / effort at the end of the line (content body first):
// {"type":"message",…,"message":{…},"usage":{…},"model":"…","effort":"…"}
// The tail anchoring is there so that lookalike text inside the message body cannot fool us.
const ASSISTANT_TAIL = /"usage":\{([^}]*)\},"model":"([^"]+)"(?:,"effort":"([^"]+)")?\}$/;

function usageFromFields(fields: string): Usage {
	const number = (key: string): number | undefined => {
		const match = new RegExp(`"${key}":(\\d+)`).exec(fields);
		return match ? Number(match[1]) : undefined;
	};
	return {
		inputTokens: number('inputTokens'),
		outputTokens: number('outputTokens'),
		cacheReadTokens: number('cacheReadTokens'),
		cacheWriteTokens: number('cacheWriteTokens'),
	};
}

// Session total cost + the last request's model/effort/usage: obtained in one streaming pass (used when resuming a session,
// so the footer is right from the start instead of waiting for the next request). Regex extraction only, no JSON.parse —
// a single transcript line can reach hundreds of KB.
export async function readSessionSeed(
	sessionId: string,
	cwd: string,
): Promise<SessionSeed | undefined> {
	let reader: ReturnType<typeof createInterface> | undefined;
	try {
		reader = createInterface({
			input: createReadStream(sessionPath(sessionId, cwd, '.jsonl'), {
				encoding: 'utf8',
			}),
			crlfDelay: Infinity,
		});
		let total = 0;
		let model: string | undefined;
		let effort: string | undefined;
		let usage: Usage | undefined;
		// Count instead of just taking 'the last one': lines carrying both usage and model exist in the transcript but
		// match no tail anchor → the line shape changed. Without this signal, format drift silently becomes 'cost reset / context gone'.
		let usageLines = 0;
		let tailHits = 0;
		for await (const line of reader) {
			if (line.includes('"costUsd"')) {
				for (const match of line.matchAll(/"costUsd":\s*([\d.eE+-]+)/g)) {
					const value = Number(match[1]);
					if (Number.isFinite(value)) total += value;
				}
			}
			if (line.includes('"usage"') && line.includes('"model"')) usageLines += 1;
			const tail = ASSISTANT_TAIL.exec(line);
			if (tail) {
				tailHits += 1;
				model = tail[2];
				effort = tail[3];
				usage = usageFromFields(tail[1]);
			}
		}
		return {costUsd: total, model, effort, usage, drifted: usageLines > 0 && tailHits === 0};
	} catch {
		return undefined;
	} finally {
		reader?.close();
	}
}

// cmdc records the 'current model + the reasoning effort per model' in ~/.commandcode/config.json:
//   {"model":"deepseek/deepseek-v4.1-flash","reasoningEffort":{"deepseek/deepseek-v4.1-flash":"high"}}
// Right after cmdc starts there is no request to ask, so the first two segments (model, effort) can only be drawn from it.
export function readUserConfig(): {model?: string; reasoningEffort: Record<string, string>} {
	// Also prototype-free: otherwise a single '__proto__' in config.json could conjure an effort out of nowhere
	const reasoningEffort: Record<string, string> = Object.create(null) as Record<string, string>;
	try {
		const parsed = JSON.parse(
			readFileSync(join(homedir(), '.commandcode', 'config.json'), 'utf8'),
		) as {model?: unknown; reasoningEffort?: unknown};
		if (parsed.reasoningEffort && typeof parsed.reasoningEffort === 'object') {
			for (const [key, value] of Object.entries(
				parsed.reasoningEffort as Record<string, unknown>,
			)) {
				if (typeof value === 'string') reasoningEffort[key] = value;
			}
		}
		return {...(typeof parsed.model === 'string' ? {model: parsed.model} : {}), reasoningEffort};
	} catch {
		return {reasoningEffort};
	}
}

