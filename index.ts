function userConfigPath(): string {
	return join(homedir(), '.commandcode', 'statusline.json');
}

function projectConfigPath(cwd: string): string {
	return join(cwd, '.commandcode', 'statusline.json');
}

type ConfigLoad = {
	readonly config: Config;
	readonly sources: readonly string[];
	/** which file last set each key (the report needs this to print the source) */
	readonly origin: Record<string, string>;
	/** file exists but cannot be read (invalid JSON / top level not an object): silently skipping would make 'I changed it and nothing happened' inexplicable */
	readonly broken: readonly string[];
};

// Notepad on Windows writes UTF-8 with a BOM and JSON.parse throws on it — such files used to be ignored entirely,
// leaving the user with 'the config had no effect' although the file content was perfectly fine. Strip it when reading.
function stripBom(text: string): string {
	return text.startsWith('\uFEFF') ? text.slice(1) : text;
}

export function loadConfig(cwd: string): ConfigLoad {
	// No prototype: otherwise a '__proto__' key in the file would change config's prototype, config[name] would read an inherited value,
	// while origin has no entry for it — making the report pass a file value off as a built-in default. Same for origin.
	const config: Config = Object.create(null) as Config;
	const origin: Record<string, string> = Object.create(null) as Record<string, string>;
	const sources: string[] = [];
	const broken: string[] = [];
	for (const path of [userConfigPath(), projectConfigPath(cwd)]) {
		let parsed: unknown;
		try {
			parsed = JSON.parse(stripBom(readFileSync(path, 'utf8')));
		} catch {
			if (existsSync(path)) broken.push(path);
			continue;
		}
		if (!parsed || typeof parsed !== 'object' || Array.isArray(parsed)) {
			broken.push(path);
			continue;
		}
		for (const [key, value] of Object.entries(parsed as Config)) {
			config[key] = value;
			origin[key] = path;
		}
		sources.push(path);
	}
	return {config, sources, origin, broken};
}

// Read-modify-write: keep the other keys in the file (including the ones we do not know — those are the user's own)
export function writeConfigKey(path: string, key: string, value: unknown): void {
	let current: Record<string, unknown> = {};
	if (existsSync(path)) {
		let parsed: unknown;
		try {
			parsed = JSON.parse(stripBom(readFileSync(path, 'utf8')));
		} catch {
			// Overwriting a broken file would erase the user's existing keys: refuse instead and let them fix it first
			throw new Error(`${path} is not valid JSON; not writing`);
		}
		if (!parsed || typeof parsed !== 'object' || Array.isArray(parsed)) {
			throw new Error(`${path} top level is not an object; not writing`);
		}
		current = parsed as Record<string, unknown>;
	}
	current[key] = value;
	mkdirSync(dirname(path), {recursive: true});
	// Write a temp file first, then rename atomically: writing the target directly could leave half a JSON behind on a crash,
	// which the next load would skip as a broken file — the user would see 'the config is gone' instead of 'the last write failed'
	const tmp = `${path}.${process.pid}.tmp`;
	try {
		writeFileSync(tmp, `${JSON.stringify(current, null, 2)}\n`, 'utf8');
		renameSync(tmp, path);
	} catch (error) {
		// A half-written tmp file left in the config dir is just garbage; failing to remove it must not hide the original error
		try {
			rmSync(tmp, {force: true});
		} catch {}
		throw error;
	}
}

// ── host version gate ───────────────────────────────────────────────────────────────
// The floor was measured, not guessed: fetched the dist/cli.mjs of two adjacent npm versions and compared them
// (1.9.0 / 1.10.0), then re-verified on 1.20 / 1.30 / 1.40 / 1.50 / 1.54.
// The latest dependency to appear is cmd.ui.capabilities — the mod relies on it to decide whether the host renders the footer at all.
// ModUi in 1.9.0 does not have this property yet (in that version capabilities only appears in the MCP protocol and prompt text),
// so cmd.ui.capabilities.status throws a TypeError outright: not a degradation, a crash. It exists from 1.10.0 on.
// Every other dependency (the modals, the subagent_stop / session_titled / config_setting_changed events,
// effort on model_request_end, the transcript tail shape, exec's signal, run_start's sessionId)
// already exists in 1.10.0; and ModUi's confirm/select/input/capabilities implementations (after normalising
// the minified identifier names) are identical in 1.10.0 and 1.54.0 — not merely present, their semantics do not drift with the version.
export const MIN_HOST_VERSION = '1.10.0';

// Host version: cmd's surface has no version field at all (probed: not among cmd's keys), so it can only be read from the
// package.json next to the CLI entry. When unreadable, return undefined — then no version check is done at all, avoiding false alarms.
export function hostVersion(): string | undefined {
	try {
		const entry = process.argv?.[1];
		if (!entry) return undefined;
		const manifest = JSON.parse(
			readFileSync(join(dirname(entry), '..', 'package.json'), 'utf8'),
		) as {name?: unknown; version?: unknown};
		// argv[1] is not necessarily cmdc (when running tests it is the test file itself): a name mismatch means no
		if (manifest.name !== 'command-code') return undefined;
		// Only accept version strings starting with a digit: '' and 'unknown' cannot be compared at all and must count as unreadable.
		// Otherwise they would parse as 0 and be compared against MIN_HOST_VERSION, declaring a perfectly good install stale and disabling it.
		if (typeof manifest.version !== 'string' || !/^\d/.test(manifest.version)) return undefined;
		return manifest.version;
	} catch {
		return undefined;
	}
}

export function versionAtLeast(actual: string, minimum: string): boolean {
	const parts = (text: string): number[] =>
		text.split('.').map(part => Number.parseInt(part, 10) || 0);
	const left = parts(actual);
	const right = parts(minimum);
	for (let index = 0; index < Math.max(left.length, right.length); index += 1) {
		const a = left[index] ?? 0;
		const b = right[index] ?? 0;
		if (a !== b) return a > b;
	}
	return true;
}

